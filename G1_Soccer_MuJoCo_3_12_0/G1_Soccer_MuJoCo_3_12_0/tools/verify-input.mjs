import assert from 'node:assert/strict';
import {InputState,ACTIONS,MOVEMENT} from '../web/input.js';
const input=new InputState();
input.press('keyboard:KeyW','KeyW');
input.press('keyboard:ArrowUp','ArrowUp');
assert.deepEqual(input.actions(),['forward']);
input.release('keyboard:KeyW');
assert.deepEqual(input.actions(),['forward']);
input.press('pointer:1','KeyA');
input.press('pointer:2','KeyQ');
input.press('keyboard:Shift','ShiftLeft');
assert.deepEqual(input.actions(),['boost','forward','left','turn_left']);
input.release('pointer:1');
assert.deepEqual(input.actions(),['boost','forward','turn_left']);
assert.equal(input.pressed('KeyW'),true);
input.clear();assert.deepEqual(input.actions(),[]);
input.press('unknown','KeyZ');assert.deepEqual(input.actions(),[]);
assert.equal(ACTIONS.Space,'kick');assert.equal(ACTIONS.KeyK,'kick');
assert.equal(MOVEMENT.ArrowLeft,'turn_left');assert.equal(MOVEMENT.KeyA,'left');
console.log('Keyboard checks passed: alias release, multiple pointers, combined directions, boost, clear, action mapping.');
